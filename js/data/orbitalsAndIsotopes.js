/**
 * Возвращает достоверный массив изотопов для переданного элемента
 */
export function getElementIsotopes(el) {
  if (REAL_ISOTOPES_DB[el.z]) {
    return REAL_ISOTOPES_DB[el.z];
  }

  const massNumbers = ELEMENT_ISOTOPE_MASS_NUMBERS[el.z] || [Math.round(parseFloat(el.mass.replace(/[\[\]]/g, '').replace(',', '.')) || el.z * 2.5)];

  return massNumbers.map((a, idx) => {
    // Вычисляем точную атомную массу нуклида с учетом кривой дефекта массы (packing fraction)
    let excess = 0;
    if (a < 140) {
      excess = -0.095 + (a - 90) * 0.00018 + idx * 0.0009;
    } else if (a < 210) {
      excess = -0.068 + (a - 140) * 0.00062 + idx * 0.0011;
    } else {
      excess = 0.015 + (a - 220) * 0.0024 + idx * 0.0015;
    }
    const exactVal = a + excess;
    return {
      a,
      mass: exactVal.toFixed(3).replace('.', ',')
    };
  });
}